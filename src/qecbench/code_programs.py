"""LR-QAOA programs for a QEC code structure on a device with qubit reuse (Quantinuum Helios).

One layer is one round of syndrome extraction, run batch by batch (``codes.schedule``). The
checks of a batch touch disjoint data qubits, so their gadgets are independent: the batch
allocates its ancillas together, applies the CNOTs in rounds (the ``j``-th support qubit of
every check at once), rotates and measures the whole batch with one ``measure_array``, and
applies the corrections. At most one batch of ancillas exists at a time, so a program holds
``n_data + largest batch`` qubits. A batch as large as the device's parallel capacity keeps
its operation zones busy, whereas one fresh ancilla per check, measured before the next is
allocated, leaves all but one idle.

``direct`` runs each check as a CNOT ladder onto its last support qubit, ``RZ(2 w gamma)`` and
the ladder undone, batch by batch in the same order, with no ancilla.

Two emitters read the same plan, so they cannot drift apart:

* ``guppy_source`` writes a Guppy module: one function per batch, taking the layer's angle,
  and ``main`` calling them layer by layer. Generated as source because Guppy cannot index a
  compile-time list with a runtime loop variable; writing one function per batch keeps the
  program ``p`` times smaller than spelling every layer out (about 750 lines for the 91-qubit
  colour code at ``p = 10``, compiled in ~13 s).
* ``qiskit_program`` builds the same circuit, gate for gate, with a reused and reset pool of
  ancillas, for local simulation on Aer.

Bit ``i`` of the result register ``c`` is data qubit ``i``.
"""

from __future__ import annotations

import importlib.util
import math
import tempfile
from pathlib import Path

from .lrqaoa import angles


def cx_rounds(checks):
    """``[[(data, position in batch), ...], ...]``: round ``j`` holds each check's ``j``-th qubit."""
    rounds = []
    for j in range(max(map(len, checks))):
        rounds.append([(c[j], a) for a, c in enumerate(checks) if j < len(c)])
    return rounds


def guppy_source(code, sched, depth: int, delta: float = 0.5, kind: str = "mcm") -> str:
    """The Guppy module (as text) of one program; ``main`` is its entry point."""
    n = code.n_data
    gammas, betas = angles(depth, delta)
    lines = [
        '"""Generated by qecbench.code_programs: LR-QAOA on '
        f'{code.name} ({kind}), p = {depth}, delta = {delta}."""',
        "from guppylang import guppy",
        "from guppylang.std.angles import angle",
        "from guppylang.std.builtins import array, result",
        "from guppylang.std.quantum import collect_measurements, cx, h, measure_array, qubit, rx, rz, z",
        "",
    ]
    for b, batch in enumerate(sched.batches):
        checks = [code.checks[c] for c in batch]
        weights = [code.weights[c] for c in batch]
        lines += ["", "@guppy", f"def batch_{b}(qs: array[qubit, {n}], halfturns: float) -> None:"]
        if kind == "mcm":
            lines.append(f"    anc = array(qubit() for _ in range({len(checks)}))")
            for rnd in cx_rounds(checks):
                lines += [f"    cx(qs[{q}], anc[{a}])" for q, a in rnd]
            for a, w in enumerate(weights):
                lines += [f"    rz(anc[{a}], angle(halfturns * {w!r}))", f"    h(anc[{a}])"]
            lines.append("    m = collect_measurements(measure_array(anc))")
            for a, check in enumerate(checks):
                lines.append(f"    if m[{a}]:")
                lines += [f"        z(qs[{q}])" for q in check]
        elif kind == "direct":
            for check, w in zip(checks, weights):
                ladder = list(zip(check[:-1], check[1:]))
                lines += [f"    cx(qs[{u}], qs[{v}])" for u, v in ladder]
                lines.append(f"    rz(qs[{check[-1]}], angle(halfturns * {w!r}))")
                lines += [f"    cx(qs[{u}], qs[{v}])" for u, v in reversed(ladder)]
        else:
            raise ValueError(f"unknown kind {kind!r}")
    lines += ["", "", "@guppy", "def main() -> None:", f"    qs = array(qubit() for _ in range({n}))",
              f"    for i in range({n}):", "        h(qs[i])"]
    for gamma, beta in zip(gammas, betas):
        halfturns = 2 * gamma / math.pi                         # RZ(2 gamma), Guppy angles in half-turns
        lines += [f"    batch_{b}(qs, {halfturns!r})" for b in range(sched.n_batches)]
        lines += [f"    for i in range({n}):", f"        rx(qs[i], angle({-2 * beta / math.pi!r}))"]
    lines.append('    result("c", collect_measurements(measure_array(qs)))')
    return "\n".join(lines) + "\n"


def load_guppy_main(source: str, name: str = "qecbench_program"):
    """Import a generated module from a file (Guppy reads function source) and return ``main``."""
    directory = Path(tempfile.mkdtemp(prefix="qecbench_guppy_"))
    path = directory / f"{name}.py"
    path.write_text(source)
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.main


def qiskit_program(code, sched, depth: int, delta: float = 0.5, kind: str = "mcm"):
    """``guppy_source``'s program in Qiskit, gate for gate, for Aer.

    Qubits ``0..n-1`` are data; the next ``largest batch`` are the ancilla pool, reset before each
    batch reuses it. Register ``m`` holds the latest outcome of every check, ``d0`` the data bits
    (bit ``j`` = data qubit ``j``).
    """
    from qiskit import ClassicalRegister, QuantumCircuit, QuantumRegister

    n = code.n_data
    gammas, betas = angles(depth, delta)
    pool = sched.max_batch if kind == "mcm" else 0
    regs = [ClassicalRegister(code.n_checks, "m")] if kind == "mcm" else []
    data_reg = ClassicalRegister(n, "d0")
    qc = QuantumCircuit(QuantumRegister(n + pool, "q"), *regs, data_reg)
    anc = list(range(n, n + pool))
    qc.h(range(n))
    for gamma, beta in zip(gammas, betas):
        for batch in sched.batches:
            checks = [code.checks[c] for c in batch]
            weights = [code.weights[c] for c in batch]
            if kind == "mcm":
                qc.reset(anc[:len(checks)])
                for rnd in cx_rounds(checks):
                    for q, a in rnd:
                        qc.cx(q, anc[a])
                for a, w in enumerate(weights):
                    qc.rz(2 * w * gamma, anc[a])
                    qc.h(anc[a])
                for a, c in enumerate(batch):
                    qc.measure(anc[a], regs[0][c])
                for a, (c, check) in enumerate(zip(batch, checks)):
                    with qc.if_test((regs[0][c], 1)):
                        for q in check:
                            qc.z(q)
            else:
                for check, w in zip(checks, weights):
                    ladder = list(zip(check[:-1], check[1:]))
                    for u, v in ladder:
                        qc.cx(u, v)
                    qc.rz(2 * w * gamma, check[-1])
                    for u, v in reversed(ladder):
                        qc.cx(u, v)
        qc.rx(-2 * beta, range(n))
    qc.measure(range(n), data_reg)
    return qc
